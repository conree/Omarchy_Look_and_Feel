"""Portable, data-only theme adapters. All paths are home-relative targets.

Themes are compiled from palette data, never from executable theme fragments.
Adapters return plans; only the transaction layer may write them.
"""
from __future__ import annotations

from dataclasses import dataclass, field
from pathlib import Path
import configparser
import json
import re
import tomllib
import os

from transaction import FILE_TARGETS, TransactionError, _ensure_home_path
from global_font_actions import _replace_ini_value


@dataclass
class Plan:
    targets: dict[str, bytes] = field(default_factory=dict)
    pending: list[dict] = field(default_factory=list)
    surfaces: list[str] = field(default_factory=list)

    def wait(self, app, action, reason):
        self.pending.append({'app': app, 'action': action, 'reason': reason})


def read(target, missing=True):
    if target == "wezterm-config":
        from transaction import require_wezterm_location
        require_wezterm_location()
    path = _ensure_home_path(Path.home() / FILE_TARGETS[target], allow_missing_parents=True)
    try:
        if path.stat().st_size > 16 * 1024 * 1024:
            raise ValueError('appearance configuration is too large')
        return path.read_bytes()
    except FileNotFoundError:
        if missing:
            return b''
        raise


def palette(path):
    """Read a validated Omarchy colors.toml, with the stock legacy fallback."""
    source = Path(path) / 'colors.toml'
    if source.is_file():
        data = tomllib.loads(source.read_text())
    else:
        old = tomllib.loads((Path(path) / 'alacritty.toml').read_text())['colors']
        data = dict(old.get('normal', {}), **old['primary'])
        data['accent'] = data.get('blue', data['foreground'])
    required = {'background', 'foreground', 'accent'}
    if not isinstance(data, dict) or not required.issubset(data):
        raise ValueError('selected theme has no complete color palette')
    colors = {}
    for key, value in data.items():
        if key == 'mode':
            continue
        if isinstance(value, str) and re.fullmatch(r'#[0-9a-fA-F]{6}', value):
            colors[key] = value.lower()
    if not required.issubset(colors):
        raise ValueError('theme colors must use six-digit hexadecimal values')
    colors.setdefault('selection', colors['accent'])
    colors.setdefault('muted', colors['foreground'])
    colors.setdefault('lighter_background', colors['background'])
    colors['mode'] = data.get('mode') or ('light' if luminance(colors['background']) > .4 else 'dark')
    if colors['mode'] not in {'light', 'dark'}:
        raise ValueError('unsupported theme mode')
    # Theme authors can supply low-contrast foreground/selection colors. Keep
    # the palette, but choose legible foregrounds for generated controls.
    colors['foreground'] = readable(colors['foreground'], colors['background'])
    if readable(colors['foreground'], colors['lighter_background']) != colors['foreground']:
        colors['lighter_background'] = colors['background']
    colors['selection_foreground'] = readable(colors['foreground'], colors['selection'])
    return colors


def luminance(color):
    channels = [int(color[i:i + 2], 16) / 255 for i in (1, 3, 5)]
    linear = [c / 12.92 if c <= .04045 else ((c + .055) / 1.055) ** 2.4 for c in channels]
    return sum(a * b for a, b in zip(linear, (.2126, .7152, .0722)))


def readable(fg, bg):
    def ratio(a, b):
        bright, dim = sorted((luminance(a), luminance(b)), reverse=True)
        return (bright + .05) / (dim + .05)
    if ratio(fg, bg) >= 4.5:
        return fg
    return max(('#000000', '#ffffff'), key=lambda color: ratio(color, bg))


def typora_stylesheet(colors):
    c = colors
    variables = {
        'bg-color': c['background'], 'text-color': c['foreground'],
        'select-text-bg-color': c['selection'], 'select-text-font-color': c['selection_foreground'],
        'side-bar-bg-color': c['lighter_background'], 'active-file-bg-color': c['selection'],
        'active-file-text-color': c['selection_foreground'], 'active-file-border-color': c['accent'],
        'item-hover-bg-color': c['selection'], 'item-hover-text-color': c['selection_foreground'],
        'primary-color': readable(c['accent'], c['background']),
        'control-text-color': c['foreground'], 'window-border': '1px solid ' + c['muted'],
        'meta-content-color': readable(c['muted'], c['background']),
    }
    css = ['/* Generated by Look and Feel from the selected Omarchy palette. */', ':root {']
    css.extend(f'  --{key}: {value};' for key, value in variables.items())
    css.extend([
        f'  color-scheme: {c["mode"]};', '}',
        'html, body, #write, #typora-source { background: var(--bg-color); color: var(--text-color); }',
        '#write { max-width: 52rem; margin: auto; padding: 2rem; line-height: 1.6; }',
        'a { color: var(--primary-color); }',
        '::selection { background: var(--select-text-bg-color); color: var(--select-text-font-color); }',
        'blockquote { border-left: 3px solid var(--primary-color); padding-left: 1rem; }',
        'table { border-collapse: collapse; }',
        'th, td { border: 1px solid var(--meta-content-color); padding: .4rem .7rem; }',
        'pre, .md-fences, code { background: var(--side-bar-bg-color); }',
        '.cm-s-inner { background: var(--side-bar-bg-color); color: var(--text-color); }',
        '#typora-sidebar { background: var(--side-bar-bg-color); color: var(--text-color); }',
    ])
    for token, role in [('comment', 'muted'), ('string', 'green'), ('number', 'magenta'),
                        ('keyword', 'red'), ('def', 'blue'), ('variable-2', 'cyan')]:
        color = readable(c.get(role, c['foreground']), c['lighter_background'])
        css.append(f'.cm-s-inner .cm-{token} {{ color: {color}; }}')
    return ('\n'.join(css) + '\n').encode()


def ini(text, section, key, value):
    # Refuse duplicates rather than silently updating an inactive occurrence.
    parser = configparser.RawConfigParser(strict=True)
    if text.strip():
        try:
            parser.read_string(text)
        except configparser.Error as exc:
            raise ValueError('unsupported INI syntax: ' + str(exc)) from exc
    return _replace_ini_value(text, section, key, value)


def qt_palette(c):
    # QPalette's documented ColorRole order; qt5ct/qt6ct save all 21 roles.
    fg, bg, accent = c['foreground'], c['background'], c['accent']
    roles = [fg, bg, '#ffffff', bg, bg, fg, fg, fg, fg, bg, bg, '#000000',
             accent, readable(fg, accent), readable(accent, bg), readable(accent, bg),
             c['lighter_background'], '#000000', bg, fg, readable(c['muted'], bg)]
    line = ', '.join(roles)
    return ('[ColorScheme]\nactive_colors=' + line + '\ndisabled_colors=' + line
            + '\ninactive_colors=' + line + '\n').encode()


GTK_BEGIN = '/* BEGIN Look and Feel palette */'
GTK_END = '/* END Look and Feel palette */'


def gtk_stylesheet(text, c):
    from css_takeover import strip_appearance
    if GTK_BEGIN in text or GTK_END in text:
        if text.count(GTK_BEGIN) != 1 or text.count(GTK_END) != 1 or text.index(GTK_BEGIN) > text.index(GTK_END):
            raise ValueError('malformed managed GTK palette')
        a, b = text.index(GTK_BEGIN), text.index(GTK_END) + len(GTK_END)
        text = text[:a] + text[b:]
    text = strip_appearance(text).rstrip()
    fg, bg = c['foreground'], c['background']
    selected_fg = readable(fg, c['selection'])
    # Ghostty removes its window's .background class below 100% opacity.
    # Unqualified window/stack/scrolledwindow rules paint an opaque layer
    # behind its renderer, defeating native terminal background transparency.
    solid_surfaces = ', '.join('window.background' + suffix for suffix in (
        '', ' dialog', ' treeview', ' textview', ' textview text', ' .view',
        ' list', ' row', ' notebook', ' stack', ' scrolledwindow'))
    return (text + '\n\n' + GTK_BEGIN + '\n' + '\n'.join([
        f'@define-color theme_bg_color {bg};', f'@define-color theme_fg_color {fg};',
        f'@define-color theme_base_color {bg};', f'@define-color theme_text_color {fg};',
        f'@define-color theme_selected_bg_color {c["selection"]};',
        f'@define-color theme_selected_fg_color {selected_fg};',
        f'{solid_surfaces} {{ background-color: {bg}; color: {fg}; }}',
        f'headerbar, toolbar, menubar, menu, popover, popover contents, button, entry, combobox {{ background-image: none; background-color: {c["lighter_background"]}; color: {readable(fg, c["lighter_background"])}; }}',
        f'label {{ color: inherit; }}',
        f'*:selected, selection, *:checked {{ background-color: {c["selection"]}; color: {selected_fg}; }}',
        f'button:hover, row:hover {{ background-color: {c["selection"]}; color: {selected_fg}; }}',
        f'entry:focus, button:focus {{ border-color: {c["accent"]}; }}',
        f'link, link:visited {{ color: {readable(c["accent"], bg)}; }}',
        GTK_END, '',
    ])).encode()


def brave_theme_flags(raw):
    """Remove only verified, unpacked theme extensions from the user flags.

    Chromium's browser-color policy and an unpacked theme are competing theme
    owners. Other extensions and all system/managed policies are untouched.
    """
    lines = []
    for line in raw.decode().splitlines(keepends=True):
        match = re.fullmatch(r'(\s*--load-extension=)([^\r\n]+)(\r?\n)?', line)
        if not match:
            lines.append(line)
            continue
        remaining = []
        for entry in match[2].split(','):
            path = Path(entry)
            remove = False
            if path.is_absolute():
                try:
                    manifest = _ensure_home_path(path / 'manifest.json', allow_missing_leaf=False)
                    data = json.loads(manifest.read_bytes())
                    remove = isinstance(data, dict) and isinstance(data.get('theme'), dict) and not any(
                        key in data for key in ('background', 'content_scripts', 'permissions'))
                except (OSError, RuntimeError, ValueError):
                    pass
            if not remove:
                remaining.append(entry)
        if remaining:
            lines.append(match[1] + ','.join(remaining) + (match[3] or ''))
    return ''.join(lines).encode()


def onlyoffice_launcher(raw):
    text = raw.decode()
    lines = []
    for line in text.splitlines(keepends=True):
        if line.startswith('Exec='):
            # Only the reviewed native launcher grammar is rewritten.
            if not re.match(r'Exec=(?:/[^\s"]+/)?(?:onlyoffice-desktopeditors|DesktopEditors)(?:\s|$)', line):
                raise ValueError('OnlyOffice launcher uses an unsupported command wrapper')
            line = re.sub(r'(?<!\S)--custom-title-bar(?=\s|$)', '', line)
            if not re.search(r'(?<!\S)--system-title-bar(?=\s|$)', line):
                line = re.sub(r'^(Exec=\S+)', r'\1 --system-title-bar', line)
        lines.append(line)
    return ''.join(lines).encode()


def build(light, dark, selected, mode, desktop_ids, *, automatic=False):
    plan = Plan()
    active = light if selected == 'light' else dark
    # GTK applications share these settings; application names do not need
    # individual code. Existing unrelated INI keys remain intact.
    for version in (3, 4):
        target = f'gtk{version}-settings'
        text = read(target).decode()
        text = ini(text, 'Settings', 'gtk-theme-name', 'Adwaita' + ('-dark' if active['mode'] == 'dark' else ''))
        text = ini(text, 'Settings', 'gtk-application-prefer-dark-theme', '1' if active['mode'] == 'dark' else '0')
        plan.targets[target] = text.encode()
        css_target = f'gtk{version}-css'
        css = read(css_target).decode()
        try:
            plan.targets[css_target] = gtk_stylesheet(css, active)
        except ValueError as exc:
            plan.wait(f'GTK {version}', 'stylesheet-conflict', str(exc))
    plan.surfaces.append('GTK 3/4 theme settings')
    from qt_integration import prepare, active as qt_active, plugins as qt_plugins, gtk_palette_supported
    desired_integration = prepare(plan, automatic=automatic)
    for version in (5, 6):
        target = f'qt{version}ct-settings'
        integration = os.environ.get('QT_QPA_PLATFORMTHEME', '')
        active_integration = qt_active(version) or desired_integration in qt_plugins().get(version, set())
        if not read(target) and not active_integration:
            continue
        colors_target = f'qt{version}ct-colors'
        text = read(target).decode()
        text = ini(text, 'Appearance', 'custom_palette', 'true')
        text = ini(text, 'Appearance', 'color_scheme_path', str(Path.home() / FILE_TARGETS[colors_target]))
        plan.targets[target] = text.encode()
        plan.targets[colors_target] = qt_palette(active)
        integration = os.environ.get('QT_QPA_PLATFORMTHEME', '')
        if not active_integration and not gtk_palette_supported(version):
            plan.wait(f'Qt {version}', 'integration-check', 'The saved Qt palette is not active in this session. Enable a compatible qtct integration, then sign out and back in.')
        plan.surfaces.append(f'Qt {version} configuration for qt{version}ct')
    if 'org.wezfurlong.wezterm.desktop' in desktop_ids:
        from wezterm_blocks import theme as wezterm_theme
        try:
            plan.targets['wezterm-config'] = wezterm_theme(read('wezterm-config').decode(), active).encode()
            plan.surfaces.append('WezTerm color palette')
        except (OSError, ValueError, TransactionError) as exc:
            plan.wait('WezTerm', 'config-structure', str(exc))
    if any('typora' in item.casefold() for item in desktop_ids):
        plan.targets['typora-light-css'] = typora_stylesheet(light)
        plan.targets['typora-dark-css'] = typora_stylesheet(dark)
        plan.targets['typora-active-css'] = typora_stylesheet(active)
        from css_takeover import strip_appearance
        try:
            plan.targets['typora-base-user-css'] = strip_appearance(read('typora-base-user-css').decode()).encode()
        except ValueError as exc:
            plan.wait('Typora', 'stylesheet-conflict', str(exc))
        from managed_preferences import decode, encode, assert_closed
        try:
            raw = read('typora-profile', missing=False)
            data = decode('typora-profile', raw)
            data.update(theme='look-and-feel.css', darkTheme='look-and-feel.css', useSeparateDarkTheme=False)
            updated = encode('typora-profile', data)
            if decode('typora-profile', raw) != data:
                if automatic:
                    raise RuntimeError('Close Typora and press Apply once to activate its managed theme; subsequent palette changes update the stylesheet.')
                assert_closed('typora-profile', Path.home() / FILE_TARGETS['typora-profile'])
                plan.targets['typora-profile'] = updated
            plan.surfaces.append('Typora document and interface theme')
        except (OSError, ValueError, RuntimeError) as exc:
            plan.wait('Typora', 'retry-when-closed', str(exc))
    if any('brave' in item.casefold() for item in desktop_ids):
        raw = read('brave-flags')
        if raw:
            plan.targets['brave-flags'] = brave_theme_flags(raw)
    if any('onlyoffice' in item.casefold() for item in desktop_ids):
        try:
            from managed_preferences import assert_closed
            raw_settings = read('onlyoffice-settings')
            settings = ini(raw_settings.decode(), 'General', 'titlebar', 'system').encode()
            if settings != raw_settings:
                if automatic:
                    raise RuntimeError('Close OnlyOffice and press Apply once to select its native frame.')
                assert_closed('onlyoffice-settings', Path.home() / FILE_TARGETS['onlyoffice-settings'])
                plan.targets['onlyoffice-settings'] = settings
            raw = read('onlyoffice-launcher')
            if not raw:
                source = next((Path(root) / 'applications/onlyoffice-desktopeditors.desktop'
                               for root in os.environ.get('XDG_DATA_DIRS', '/usr/local/share:/usr/share').split(':')
                               if Path(root).is_absolute() and (Path(root) / 'applications/onlyoffice-desktopeditors.desktop').is_file()), None)
                if source is None:
                    raise ValueError('OnlyOffice native launcher could not be found')
                raw = source.read_bytes()
            launcher = onlyoffice_launcher(raw)
            plan.targets['onlyoffice-launcher'] = launcher
            if launcher != raw:
                try:
                    assert_closed('onlyoffice-settings', Path.home() / FILE_TARGETS['onlyoffice-settings'])
                except RuntimeError:
                    plan.wait('OnlyOffice', 'reopen', 'Reopen OnlyOffice once to use its updated native-frame launcher.')
            plan.surfaces.append('OnlyOffice native window frame')
        except (OSError, ValueError, RuntimeError) as exc:
            plan.wait('OnlyOffice', 'launcher-conflict', str(exc))
    return plan
